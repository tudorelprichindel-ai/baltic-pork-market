(window.GALAS_GROZS_CATALOG?.products || []).forEach((product) => {
  const reviewed = REVIEWED_RUSSIAN_PRODUCTS[product.id];
  if (!reviewed) return;
  for (const field of ["name", "description", "meta", "featuredDescription"]) {
    if (reviewed[field]) product[field] = { ...product[field], ru: reviewed[field] };
  }
  if (reviewed.variants && Array.isArray(product.variants)) {
    product.variants = product.variants.map((variant) => {
      const label = reviewed.variants[variant.id];
      return label ? { ...variant, label: { ...variant.label, ru: label } } : variant;
    });
  }
});

(window.GALAS_GROZS_CATALOG?.products || []).forEach((product) => {
  for (const field of ["name", "description", "meta", "featuredDescription"]) {
    const value = product[field]?.ru;
    if (!value) continue;
    product[field].ru = value
      .replace(/^(Отрезок|Отрез|Нарезка):/, "Отруб:")
      .replaceAll("свиная ветчина", "свиной окорок")
      .replaceAll("свиной ветчины", "свиного окорока");
  }
});
